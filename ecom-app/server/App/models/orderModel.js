let mongoose=require("mongoose")
let orderSchema=mongoose.Schema(
    {
        userId:{
            type:mongoose.Schema.Types.ObjectId,
            ref:"User",
            required:true
        },
        orderItems:[],
        shippingAddress:{
            type:Object,
            required:true
        },
        paymentMethod:{
            type:String,
            required:true,
            enum:["cod","online"]
        },
        orderStatus:{
            type:String,
            default:"pending",
            enum:["pending","processing","delivered","success","failed"]
        },
        paymentStatus:{
            type:String,
            default:"pending",
            enum:["pending","success","failed"]
        },
        razorpayPaymentId:{
            type:String
        },
        razorpayOrderId:{
            type:String
        },
        totalAmount:{
            type:Number,
            required:true
        }
    },
    {
        timestamps:true
    }
)
let orderModel=mongoose.model("order",orderSchema)
module.exports=orderModel